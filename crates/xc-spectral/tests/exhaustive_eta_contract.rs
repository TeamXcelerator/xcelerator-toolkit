#[cfg(feature = "hp")]
#[test]
fn exhaustive_hp_eta_intermediate_underflow_preserves_final_precision() {
    use rug::{float::Constant, Float};
    let p = 192;
    // exp(-t) is about 3/4 of MPFR's smallest positive number, while
    // t*exp(-t) is representable with full precision.
    let mut argument = Float::with_val(p + 128, Constant::Log2);
    argument *= 1_i64 - i64::from(rug::float::exp_min());
    argument += (Float::with_val(p + 128, 4) / 3u32).ln();
    let t = Float::with_val(p, argument);
    let work = p + 128;
    let mut log_expected = Float::with_val(work, &t).ln();
    log_expected -= &t;
    let scale_exp = i64::from(rug::float::exp_min()) + 32;
    let mut log_scale = Float::with_val(work, Constant::Log2);
    log_scale *= scale_exp;
    log_expected -= log_scale;
    let expected_scaled = log_expected.exp();
    let mut actual_scaled = Float::with_val(work, xc_spectral::mellin::omega_hp(&t));
    actual_scaled <<= u32::try_from(-scale_exp).unwrap();
    let relative = (actual_scaled / expected_scaled - 1u32).abs();
    assert!(
        relative < (Float::with_val(work, 1) >> (p - 8)),
        "relative error: {relative}"
    );
}
